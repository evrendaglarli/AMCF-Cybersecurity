"""Statistical inference routines for AMCF.

R14 audit correction: use an actual BCa bootstrap for event recall and a
paired, correlated DeLong ROC-AUC comparison.  No benchmark values are stored
or generated by this module.
"""
from __future__ import annotations

from typing import Tuple
import numpy as np
from scipy import stats


def _binary_arrays(y_true, y_pred):
    true = np.asarray(y_true)
    pred = np.asarray(y_pred)
    if true.ndim != 1 or pred.ndim != 1 or len(true) != len(pred) or len(true) == 0:
        raise ValueError('Nonempty, equal-length, one-dimensional arrays required.')
    if not np.isin(true, [0, 1]).all() or not np.isin(pred, [0, 1]).all():
        raise ValueError('y_true and y_pred must have binary 0/1 values.')
    return true, pred


def bootstrap_ci(y_true, y_pred, n_bootstrap: int = 10000, ci: float = 0.95,
                 random_state: int | None = 42) -> Tuple[float, float]:
    """BCa CI for event-level recall, resampling the positive event class.

    The resampling unit is an event, not an incident or time block.  This must
    NOT be presented as a block/cluster CI for temporally dependent streams.
    A degenerate class with all successes or all misses cannot produce a valid
    two-sided BCa interval; callers must choose a documented alternative.
    """
    true, pred = _binary_arrays(y_true, y_pred)
    successes = (pred[true == 1] == 1).astype(float)
    if len(successes) < 3:
        raise ValueError('BCa recall CI requires at least 3 positive events.')
    if np.all(successes == successes[0]):
        raise ValueError('BCa interval is degenerate (all positives correctly detected or all missed).')
    if not (0.0 < ci < 1.0) or n_bootstrap < 100:
        raise ValueError('Provide 0<ci<1 and at least 100 resamples.')
    res = stats.bootstrap((successes,), np.mean, n_resamples=n_bootstrap,
                          confidence_level=ci, method='BCa',
                          random_state=np.random.default_rng(random_state))
    low, high = res.confidence_interval.low, res.confidence_interval.high
    if not np.isfinite([low, high]).all():
        raise ValueError('BCa interval is undefined for these data.')
    return float(low), float(high)


def bootstrap_ci_precision(y_true, y_pred, n_bootstrap: int = 10000,
                           random_state: int | None = 42) -> Tuple[float, float]:
    """Percentile (not BCa) bootstrap CI for event-level binary precision."""
    true, pred = _binary_arrays(y_true, y_pred)
    rng = np.random.default_rng(random_state)
    vals = []
    for _ in range(n_bootstrap):
        ix = rng.integers(len(true), size=len(true))
        mask = pred[ix] == 1
        if mask.any():
            vals.append(np.mean(true[ix][mask] == 1))
    if not vals:
        raise ValueError('No positive predictions in any bootstrap sample.')
    return tuple(float(x) for x in np.percentile(vals, [2.5, 97.5]))


def bootstrap_ci_median(data, n_bootstrap: int = 10000,
                        random_state: int | None = 42) -> Tuple[float, float]:
    """Percentile bootstrap for a median of directly observed durations."""
    a = np.asarray(data, dtype=float)
    if a.ndim != 1 or len(a) == 0 or not np.isfinite(a).all():
        raise ValueError('Finite, nonempty duration vector required.')
    rng = np.random.default_rng(random_state)
    vals = [np.median(rng.choice(a, size=len(a), replace=True))
            for _ in range(n_bootstrap)]
    return tuple(float(x) for x in np.percentile(vals, [2.5, 97.5]))


def _midranks(x):
    """One-based average ranks for ties, used by paired DeLong."""
    x = np.asarray(x, dtype=float)
    order = np.argsort(x, kind='mergesort')
    sorted_x = x[order]
    ranks = np.empty(len(x), dtype=float)
    i = 0
    while i < len(x):
        j = i + 1
        while j < len(x) and sorted_x[j] == sorted_x[i]:
            j += 1
        ranks[order[i:j]] = (i + j - 1) / 2 + 1
        i = j
    return ranks


def delong_test(y_true, y_score1, y_score2) -> float:
    """Two-sided *paired* DeLong p-value for correlated ROC-AUCs.

    Implements placement-value covariance, not a permutation of labels and
    scores together.  The two models must score the SAME labeled examples.
    """
    y = np.asarray(y_true)
    a = np.asarray(y_score1, dtype=float)
    b = np.asarray(y_score2, dtype=float)
    if any(z.ndim != 1 for z in (y, a, b)) or not (len(y) == len(a) == len(b)):
        raise ValueError('All inputs must be equally sized 1D arrays.')
    if not np.isin(y, [0, 1]).all() or not np.isfinite(a).all() or not np.isfinite(b).all():
        raise ValueError('Binary labels and finite scores required.')
    m, n = int(np.sum(y == 1)), int(np.sum(y == 0))
    if min(m, n) < 2:
        raise ValueError('Paired DeLong covariance requires >=2 cases in each class.')
    if np.array_equal(a, b):
        return 1.0
    indices = np.r_[np.flatnonzero(y == 1), np.flatnonzero(y == 0)]
    scores = np.vstack((a[indices], b[indices]))
    tx = np.vstack([_midranks(x[:m]) for x in scores])
    ty = np.vstack([_midranks(x[m:]) for x in scores])
    tz = np.vstack([_midranks(x) for x in scores])
    aucs = (tz[:, :m].sum(axis=1) / m - (m + 1) / 2.0) / n
    v01 = (tz[:, :m] - tx) / n
    v10 = 1.0 - (tz[:, m:] - ty) / m
    cov = np.cov(v01) / m + np.cov(v10) / n
    delta_var = float(cov[0, 0] + cov[1, 1] - 2 * cov[0, 1])
    if delta_var <= 1e-15:
        if np.isclose(aucs[0], aucs[1], atol=1e-12):
            return 1.0
        raise ValueError('DeLong covariance is degenerate for unequal AUCs.')
    z = abs(float(aucs[0] - aucs[1])) / np.sqrt(delta_var)
    return float(2 * stats.norm.sf(z))


def holm_bonferroni_correction(p_values, alpha: float = 0.05):
    """Monotone Holm adjusted p-values and corresponding rejection decisions."""
    p = np.asarray(p_values, dtype=float)
    if p.ndim != 1 or not np.isfinite(p).all() or ((p < 0) | (p > 1)).any():
        raise ValueError('p_values must be a 1D array in [0,1].')
    order = np.argsort(p)
    steps = (len(p) - np.arange(len(p))) * p[order]
    corrected = np.minimum(1.0, np.maximum.accumulate(steps))
    adjusted = np.empty(len(p), dtype=float)
    adjusted[order] = corrected
    return adjusted, adjusted <= alpha


def newey_west_se(residuals, lag: int = 7) -> float:
    """HAC standard error for a mean of centered residuals."""
    x = np.asarray(residuals, dtype=float)
    if x.ndim != 1 or len(x) < 2 or not np.isfinite(x).all() or lag < 0:
        raise ValueError('At least two finite observations and nonnegative lag required.')
    x = x - x.mean()
    n = len(x)
    lag = min(lag, n - 1)
    gamma0 = np.dot(x, x) / n
    long_run_var = gamma0
    for k in range(1, lag + 1):
        cov = np.dot(x[k:], x[:-k]) / n
        long_run_var += 2 * (1 - k / (lag + 1)) * cov
    return float(np.sqrt(max(long_run_var, 0.0) / n))


def compute_confidence_interval(values, ci: float = 0.95):
    """Percentile interval of a precomputed empirical statistic distribution."""
    a = np.asarray(values, dtype=float)
    if a.ndim != 1 or not len(a) or not np.isfinite(a).all() or not (0 < ci < 1):
        raise ValueError('Finite samples and 0<ci<1 required.')
    lower, upper = np.percentile(a, [(1 - ci) * 50, (1 + ci) * 50])
    return float(lower), float(upper)